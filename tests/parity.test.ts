// Parity with the old page: the typed core, fed the real generated site-data, must reproduce the leaderboard
// numbers in docs/rewrite/golden-numbers.json (rank, overall, tier scores, runs, in-progress and
// provisional flags, time, tok/s, cost) for v4 and v3: the chat, agentic and Combined sections, the
// provisional on/off and tier-excluded scenarios, sort orders and single-filter boards. Differences are
// allowed only when an allowlist rule in tests/allowlist.ts explains them; anything else fails.
//
// WRITE_GOLDEN_DIFF=1 npm test  rewrites docs/rewrite/golden-diff.md from the allowed differences.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { B03_MODELS, ECLIPSE_COST_MODELS, RULES, classify, type Rule } from './allowlist';
import { ROOT, haveData, loadIndex, runScenarios, type Diff, type ScenarioRun } from './golden';

if (!haveData()) {
  throw new Error(
    'No site data at static/data. Run `npm run data` (see README) or generate it with `crucible site-data`.',
  );
}

const runs: ScenarioRun[] = runScenarios();

const fmt = (v: unknown) => (typeof v === 'number' ? String(Math.round(v * 1e6) / 1e6) : JSON.stringify(v));

describe('golden parity', () => {
  const groups = new Map<string, ScenarioRun[]>();
  for (const r of runs) {
    const k = `${r.suite} ${r.mode}`;
    groups.set(k, [...(groups.get(k) ?? []), r]);
  }
  for (const [name, list] of groups) {
    it(`${name}: every difference is allowlisted`, () => {
      const bad: Diff[] = [];
      for (const r of list) for (const d of r.diffs) if (!classify(d)) bad.push(d);
      expect(
        bad
          .slice(0, 20)
          .map((d) => `${d.scenario} ${d.row} ${d.field} golden=${fmt(d.golden)} actual=${fmt(d.actual)}`),
      ).toEqual([]);
    });
  }

  it('the B-03 cause is real: those models have setups with unrecorded fields, or registry-level grouping', () => {
    const idx = loadIndex('v4');
    for (const model of Object.keys(B03_MODELS)) {
      const setups = Object.values(idx.entities.setups).filter((s) => s.model === model);
      expect(setups.length).toBeGreaterThan(1);
      if (model !== 'openai/gpt-oss-20b') expect(setups.some((s) => s.unrecorded.length > 0)).toBe(true);
    }
  });

  it('Combined time, tok/s and cost match golden exactly except for the B-03 rows', () => {
    const bad = runs
      .filter((r) => r.mode === 'combined')
      .flatMap((r) => r.diffs)
      .filter((d) => ['time', 'tps', 'cost'].includes(d.field))
      .filter((d) => classify(d)?.id !== 'B-03' && classify(d)?.id !== 'eclipse-cost');
    expect(bad).toEqual([]);
  });

  it('covers the whole golden leaderboard', () => {
    expect(runs.length).toBe(84);
    expect(runs.reduce((n, r) => n + r.rowsGolden, 0)).toBeGreaterThan(3000);
  });

  it('every allowlist rule is still needed', () => {
    const used = new Set<string>();
    for (const r of runs) for (const d of r.diffs) used.add(classify(d)?.id ?? '');
    expect(RULES.map((r) => r.id).filter((id) => !used.has(id))).toEqual([]);
  });
});

// ---- docs/rewrite/golden-diff.md ----

function table(rows: string[][]): string {
  const [head, ...body] = rows;
  return [head!, head!.map(() => '---'), ...body].map((r) => `| ${r.join(' | ')} |`).join('\n');
}

export function goldenDiffMarkdown(): string {
  const all = runs.flatMap((r) => r.diffs);
  const byRule = new Map<Rule, Diff[]>();
  for (const d of all) {
    const rule = classify(d);
    if (rule) byRule.set(rule, [...(byRule.get(rule) ?? []), d]);
  }
  const compared = runs.reduce((n, r) => n + r.rowsGolden, 0);
  const board = (d: Diff) => d.row.includes('#') && !d.scenario.includes('|filter');
  const key = (d: Diff) => `${d.suite}|${d.mode}|${d.scenario}|${d.row.toLowerCase()}`;
  const rowsWithDiff = new Set(all.filter((d) => board(d) && d.field !== 'rank').map(key));
  const rowsRankOnly = new Set(all.filter((d) => board(d) && d.field === 'rank').map(key));
  for (const k of rowsWithDiff) rowsRankOnly.delete(k);
  const out: string[] = [];
  out.push('# Golden diff: what the new core does differently from the old page', '');
  out.push(
    '_Generated by `WRITE_GOLDEN_DIFF=1 npm test` from `tests/parity.test.ts`; do not edit by hand. Each allowed difference matches exactly one rule in `tests/allowlist.ts`; a difference with no rule fails the test._',
    '',
  );
  out.push(
    `The test reproduces ${runs.length} leaderboard scenarios of \`golden-numbers.json\` (suites v4 and v3, sections chat, agentic and Combined, provisional off and on, each tier left out in turn, in-progress rows hidden and shown) plus sort orders, single-filter boards (harness, where, hw, reasoning) and facet counts. That is ${compared} golden rows; ${compared - rowsWithDiff.size - rowsRankOnly.size} match on every compared field, ${rowsRankOnly.size} differ only in rank (shifted by the rows above them) and ${rowsWithDiff.size} carry another allowed difference. Rows are matched by model and reasoning level, ignoring case.`,
    '',
    'Not compared, because the value grammar changed rather than the numbers: filters on `format`, `quant` and `packager` (the page guessed `splash`, `mlx-4bit` and publisher spellings; the registry now records `mlx`, `4bit`, the packager). Time, tok/s and cost are compared on non-excluded scenarios only, because the old page ignored the tier toggles for them. Combined time, tok/s and cost are the exact pooled values from site-data and match golden everywhere the setups correspond; the only differences are the four B-03 rows (`openai/gpt-oss-20b#low`, `qwen/qwen3.5-9b#default`, `qwen/qwen3.6-35b-a3b#on`, `qwen/qwen3.8-27b#xhigh`), whose runs the registry groups differently.',
    '',
  );
  out.push(
    'Also expected, with no numeric difference: **B-14** (the Granite maker is `ibm-granite` everywhere, was `ibm` in some paths) changes a label, not a row key or a score; **B-07** (rank is always rank by Overall) is the rank definition used here, and since the golden boards are sorted by Overall it only shows as the rank shifts below.',
    '',
  );
  out.push('## Rules', '');
  out.push(
    table([
      ['Rule', 'Allowed diffs', 'Distinct rows', 'Why'],
      ...RULES.map((r) => {
        const list = byRule.get(r) ?? [];
        return [
          `\`${r.id}\``,
          String(list.length),
          String(new Set(list.map((d) => `${d.suite}|${d.mode}|${d.row}`)).size),
          r.reason.replace(/\|/g, '/'),
        ];
      }),
    ]),
    '',
  );

  out.push('## B-03: models whose setups changed identity', '');
  out.push(
    table([['Model', 'Cause'], ...Object.entries(B03_MODELS).map(([m, why]) => [`\`${m}\``, why])]),
    '',
  );
  out.push('## Eclipse cost and hardware', '');
  out.push(
    table([['Model', 'Setups'], ...Object.entries(ECLIPSE_COST_MODELS).map(([m, why]) => [`\`${m}\``, why])]),
    '',
  );

  out.push('## Every allowed difference', '');
  out.push(
    'Identical differences repeat across scenarios (for example the provisional off and on boards); each is listed once with the number of scenarios it appears in. Rank shifts are not listed row by row: they follow from the rows above, and the test checks each one exactly (see `B-03-rank`).',
    '',
  );
  for (const rule of RULES) {
    const list = byRule.get(rule) ?? [];
    if (!list.length) continue;
    out.push(`### \`${rule.id}\`: ${rule.title}`, '');
    if (rule.id === 'B-03-rank') {
      const rows = new Set(list.map((d) => `${d.suite}|${d.mode}|${d.row}`));
      out.push(
        `${list.length} rank differences over ${rows.size} rows, all explained by the rows of the models above.`,
        '',
      );
      continue;
    }
    const dedup = new Map<string, { d: Diff; n: number }>();
    for (const d of list) {
      const key = [d.suite, d.mode, d.row, d.field, fmt(d.golden), fmt(d.actual)].join('\u0000');
      const e = dedup.get(key);
      if (e) e.n += 1;
      else dedup.set(key, { d, n: 1 });
    }
    const rows = [...dedup.values()].sort((a, b) =>
      [a.d.suite, a.d.mode, a.d.row, a.d.field].join('|') <
      [b.d.suite, b.d.mode, b.d.row, b.d.field].join('|')
        ? -1
        : 1,
    );
    out.push(
      table([
        ['Suite', 'Section', 'Row / board', 'Field', 'Golden', 'Now', 'Scenarios'],
        ...rows.map(({ d, n }) => [
          d.suite,
          d.mode,
          `\`${d.row}\``,
          d.field,
          fmt(d.golden),
          fmt(d.actual),
          String(n),
        ]),
      ]),
      '',
    );
  }
  return out.join('\n');
}

if (process.env.WRITE_GOLDEN_DIFF) {
  it('writes golden-diff.md', () => {
    writeFileSync(resolve(ROOT, 'docs/rewrite/golden-diff.md'), goldenDiffMarkdown() + '\n');
  });
}
